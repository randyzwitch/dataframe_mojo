"""Generate allocation-free Unicode 17 normalization lookup tables.

Download UnicodeData.txt and DerivedNormalizationProps.txt from
https://www.unicode.org/Public/17.0.0/ucd/ into --ucd, then run this script.
Run with `pixi run python3 scripts/normalization_tables.py --ucd DIRECTORY`.
Each integer uses seven bits per ASCII byte, so Mojo's static StringSlice
can reference the tables directly, without decoding/allocating whole tables.
"""
import argparse
import hashlib
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def pack(value, width):
    assert 0 <= value < 1 << (7 * width)
    return bytes((value >> (7 * i)) & 127 for i in range(width))


def literal(name, data):
    lines = [f"comptime {name} = ("]
    for offset in range(0, len(data), 24):
        lines.append('    "' + ''.join(f'\\x{b:02x}' for b in data[offset:offset+24]) + '"')
    lines.append(')')
    return '\n'.join(lines)


def generate(directory):
    records = {}
    properties = [0] * 0x110000
    for line in (directory / 'UnicodeData.txt').read_text().splitlines():
        fields = line.split(';')
        cp, ccc = int(fields[0], 16), int(fields[3])
        properties[cp] = ccc
        if fields[5]:
            parts = fields[5].split()
            compat = parts[0].startswith('<')
            if compat:
                parts = parts[1:]
            records[cp] = (compat, [int(part, 16) for part in parts])
    excluded = set()
    shifts = {'NFC_QC': 8, 'NFD_QC': 10, 'NFKC_QC': 11, 'NFKD_QC': 13}
    for line in (directory / 'DerivedNormalizationProps.txt').read_text().splitlines():
        line = line.split('#')[0].strip()
        if not line:
            continue
        fields = [x.strip() for x in line.split(';')]
        ends = fields[0].split('..')
        lo, hi = int(ends[0], 16), int(ends[-1], 16)
        if fields[1] == 'Full_Composition_Exclusion':
            excluded.update(range(lo, hi + 1))
        if fields[1] in shifts:
            # 0: yes (the default), 1: no, 2: maybe.
            value = 1 if fields[2] == 'N' else 2
            for cp in range(lo, hi + 1):
                properties[cp] |= value << shifts[fields[1]]
    stage1, stage2, pages = bytearray(), bytearray(), {}
    for start in range(0, 0x110000, 256):
        page = b''.join(pack(x, 2) for x in properties[start:start+256])
        if page not in pages:
            pages[page] = len(pages)
            stage2.extend(page)
        stage1.extend(pack(pages[page], 2))
    index, values, pairs = bytearray(), bytearray(), []
    for cp, (compat, decomposition) in sorted(records.items()):
        assert len(decomposition) < 64
        index.extend(pack(cp, 3) + pack(len(values) // 3, 3) + pack(len(decomposition) | (64 if compat else 0), 1))
        values.extend(b''.join(pack(x, 3) for x in decomposition))
        if not compat and len(decomposition) == 2 and cp not in excluded:
            pairs.append((*decomposition, cp))
    ids = [0] * 0x110000
    for i, cp in enumerate(sorted(records)):
        ids[cp] = i + 1
    decomp_pages, decomp_ids, seen = bytearray(), bytearray(), {}
    for start in range(0, 0x110000, 256):
        page = b''.join(pack(x, 2) for x in ids[start:start+256])
        if page not in seen:
            seen[page] = len(seen)
            decomp_ids.extend(page)
        decomp_pages.extend(pack(seen[page], 2))
    assert all(b >= 128 for _, b, _ in pairs), 'ASCII second elements need a composition lookup'
    size = 2048
    while True:
        slots = [None] * size
        for a, b, cp in pairs:
            at = ((a * 0x9E3779B1) ^ b) & (size - 1)
            while slots[at] is not None:
                at = (at + 1) & (size - 1)
            slots[at] = (a, b, cp)
        run = longest = 0
        for slot in slots + slots:
            run = run + 1 if slot is not None else 0
            longest = max(longest, run)
        if longest <= 16:
            break
        size *= 2
    composition = b''.join(pack(a, 3) + pack(b, 3) + pack(cp, 3) if entry else bytes(9) for entry in slots for a, b, cp in [entry or (0, 0, 0)])
    out = ['"""Unicode 17.0 normalization tables; generated by scripts/normalization_tables.py.', '',
           'Source: https://www.unicode.org/Public/17.0.0/ucd/.',
           'ASCII seven-bit packing permits static, allocation-free lookup.',
           'Copyright 1991-2026 Unicode, Inc.; see scripts/vendor/unicode-LICENSE.']
    for name in ['UnicodeData.txt', 'DerivedNormalizationProps.txt']:
        out.append(name + ' SHA256: ' + hashlib.sha256((directory/name).read_bytes()).hexdigest())
    out.extend(['"""', '', ''])
    out.extend(literal(name, data) + '\n\n' for name, data in [('_PAGES', stage1), ('_PROPS', stage2), ('_DECOMP', index), ('_VALUES', values), ('_DECOMP_PAGES', decomp_pages), ('_DECOMP_IDS', decomp_ids), ('_COMPOSE', composition)])
    out.append(f'comptime _COMPOSE_MASK = {size - 1}\n')
    out.append('''@always_inline
def _read2(data: StringSlice, at: Int) -> Int:
    var p = data.as_bytes().unsafe_ptr()
    return Int(p[unsafe_offset=at]) | (Int(p[unsafe_offset=at + 1]) << 7)


@always_inline
def _read3(data: StringSlice, at: Int) -> Int:
    var p = data.as_bytes().unsafe_ptr()
    return Int(p[unsafe_offset=at]) | (Int(p[unsafe_offset=at + 1]) << 7) | (Int(p[unsafe_offset=at + 2]) << 14)


@always_inline
def properties(cp: Int) -> Int:
    if cp < 128:
        return 0
    var page = _read2(StringSlice(_PAGES), 2 * (cp >> 8))
    return _read2(StringSlice(_PROPS), 512 * page + 2 * (cp & 255))


@always_inline
def decomposition(cp: Int, compatible: Bool) -> Tuple[Int, Int]:
    var page = _read2(StringSlice(_DECOMP_PAGES), 2 * (cp >> 8))
    var index = _read2(StringSlice(_DECOMP_IDS), 512 * page + 2 * (cp & 255)) - 1
    if index < 0:
        return (0, 0)
    var data = StringSlice(_DECOMP)
    var size = Int(data.as_bytes().unsafe_ptr()[unsafe_offset=7 * index + 6])
    if (size & 64) != 0 and not compatible:
        return (0, 0)
    return (_read3(data, 7 * index + 3), size & 63)


@always_inline
def decomposition_value(index: Int) -> Int:
    return _read3(StringSlice(_VALUES), 3 * index)


@always_inline
def composition(a: Int, b: Int) -> Int:
    # Generated open-addressing table; the longest occupied run is <=16.
    var data = StringSlice(_COMPOSE)
    var slot = ((a * 0x9E3779B1) ^ b) & _COMPOSE_MASK
    while True:
        var at = 9 * slot
        var cp = _read3(data, at + 6)
        if cp == 0:
            return -1
        if _read3(data, at) == a and _read3(data, at + 3) == b:
            return cp
        slot = (slot + 1) & _COMPOSE_MASK
''')
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ucd', required=True, type=Path)
    parser.add_argument('--output', type=Path, default=ROOT/'dataframe/unicode_normalization_tables.mojo')
    args = parser.parse_args()
    args.output.write_text(generate(args.ucd))
    subprocess.run(['mblack', '--target-version', 'mojo', '--line-length', '80', str(args.output)], check=True)
    source = args.ucd / 'NormalizationTest.txt'
    if source.exists():
        rows = []
        for line in source.read_text().splitlines():
            line = line.split('#')[0].strip()
            if line and not line.startswith('@'):
                rows.append(';'.join(f.strip() for f in line.split(';')[:5]))
        fixture = ROOT / 'tests/fixtures/unicode/normalization-17.0.0.txt'
        fixture.parent.mkdir(parents=True, exist_ok=True)
        fixture.write_text('# Unicode 17.0.0 NormalizationTest.txt; copyright Unicode, Inc.\n# License: scripts/vendor/unicode-LICENSE\n# Source https://www.unicode.org/Public/17.0.0/ucd/NormalizationTest.txt\n# SHA256 ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n' + '\n'.join(rows) + '\n')
    print(args.output)


if __name__ == '__main__':
    main()
