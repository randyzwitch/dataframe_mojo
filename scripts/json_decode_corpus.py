"""Generate scalar JSON decoding contracts from the independent Polars oracle.

Run with pixi run -e oracle python3 scripts/json_decode_corpus.py.
Values are encoded as physical integers, exact float bits, or UTF8 hex.
"""
from pathlib import Path
import json
import struct
import decimal
import random
import polars as pl


def main():
    decimal.getcontext().prec = 100
    types = {
        name.lower(): getattr(pl, name)
        for name in (
            "Int8",
            "Int16",
            "Int32",
            "Int64",
            "Int128",
            "UInt8",
            "UInt16",
            "UInt32",
            "UInt64",
            "Float32",
            "Float64",
            "Boolean",
            "String",
            "Date",
            "Time",
            "Categorical",
        )
    }
    for unit in ("ms", "us", "ns"):
        types[f"datetime_{unit}"] = pl.Datetime(unit)
        types[f"duration_{unit}"] = pl.Duration(unit)
    types["datetime_utc"] = pl.Datetime("us", "UTC")
    types["datetime_fixed"] = pl.Datetime("us", "+05:30")
    types["datetime_iana"] = pl.Datetime("us", "America/New_York")
    for precision, scale in ((8, 2), (20, 5), (38, 8)):
        types[f"decimal_{precision}_{scale}"] = pl.Decimal(precision, scale)
    documents = [
        "null",
        "true",
        "false",
        "0",
        "-0",
        "0.0",
        "-0.0",
        "1",
        "-1",
        "1.9",
        "-1.9",
        "127.9",
        "128",
        "-128.9",
        "255",
        "256",
        "32768",
        "-32769",
        "2147483647",
        "2147483648",
        "4294967295",
        "9223372036854775807",
        "9223372036854775808",
        "-9223372036854775808",
        "18446744073709551615",
        "18446744073709551616",
        "170141183460469231731687303715884105727",
        "-170141183460469231731687303715884105728",
        "340282366920938463463374607431768211455",
        "340282366920938463463374607431768211456",
        "1e40",
        "1e400",
        "1e-400",
        "1e20",
        "1e-7",
        "2.675",
        "2.685",
        "0.005",
        "-1.245",
        "1.245",
        "1.255",
        "86399999999999",
        "86400000000000",
        "[]",
        "{}",
        "[1,]",
        "01",
        '"\\uD800"',
        "1e0",
        "-0e0",
        "-0.5",
        "65535",
        "65536",
        "-2147483649",
        "1.7976931348623157e308",
        "5e-324",
    ]
    documents += [
        json.dumps(s, ensure_ascii=False)
        for s in (
            "",
            "bad",
            "1",
            "1.245",
            "1.255",
            "-1.245",
            "1e2",
            "1e-4",
            "1000000000000000000000000000000",
            "é\n😀",
            "1970-01-02",
            "2000-02-29",
            "2001-02-29",
            "12:34:56.123456789",
            "24:00:00",
            "1970-01-01T00:00:01",
            "1970-01-01T00:00:01Z",
            "1970-01-01T00:00:01+05:30",
            "1970-01-01 00:00:01",
            "2020-02-29T12:00:00.123456789Z",
        )
    ]
    rng = random.Random(798)
    documents += [
        json.dumps(rng.uniform(-10, 10) * 10 ** rng.randrange(-300, 300))
        for _ in range(32)
    ]
    rows = []
    for name, dtype in types.items():
        for document in documents:
            try:
                result = pl.Series([document]).str.json_decode(dtype)
                if result.null_count() == 1:
                    cell = "NULL"
                elif name.startswith("float"):
                    bits = struct.unpack("<Q", struct.pack("<d", result[0]))[0]
                    cell = "F" + str(bits)
                elif dtype.is_temporal():
                    cell = "I" + str(result.to_physical()[0])
                elif name.startswith("decimal"):
                    cell = "I" + str(int(result[0].scaleb(dtype.scale)))
                elif name in ("string", "categorical"):
                    cell = "S" + result[0].encode().hex()
                elif name == "boolean":
                    cell = "B1" if result[0] else "B0"
                else:
                    cell = "I" + str(result[0])
            except Exception:
                cell = "ERROR"
            rows.append("\t".join((name, document.encode().hex(), cell)))
    destination = (
        Path(__file__).resolve().parents[1]
        / "tests/fixtures/json_strings/decode.tsv"
    )
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        f"# Polars {pl.__version__}; generated by scripts/json_decode_corpus.py\n"
        + "\n".join(rows)
        + "\n"
    )
    print(len(rows), "typed JSON oracle cases", destination)


if __name__ == "__main__":
    main()
