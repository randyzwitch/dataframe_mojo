"""Write dataframe/regex/unicode_tables.mojo: the code point sets behind the
regex engine's Unicode \\w, \\d and \\s, and its simple case-folding orbits.

The generator tests every scalar value against `^\\w$`, `^\\d$` and `^\\s$`,
and every code point with a case mapping against `(?i)^\\x{...}$`. Matching
code points are compressed into range sets, preserving the Unicode behavior
of the generated tables. Run it in the oracle environment:

    pixi run -e oracle python3 scripts/regex_unicode_tables.py
"""
from pathlib import Path

import polars as pl

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "dataframe" / "regex" / "unicode_tables.mojo"


def ranges(members: list[int]) -> list[list[int]]:
    out: list[list[int]] = []
    for c in members:
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def numeric_constructor(name: str, values: list[int]) -> str:
    lines = ["def %s() -> List[UInt32]:" % name, "    return ["]
    lines.extend("        0x%X," % cp for cp in values)
    lines.append("    ]")
    return "\n".join(lines)


def render(
    sets: dict[str, list[list[int]]], pairs: list[tuple[int, int]], version: str
) -> str:
    text = [
        '"""Unicode tables for the regex engine, generated by',
        "scripts/regex_unicode_tables.py from Polars %s (Rust `regex`)."
        % version,
        "",
        "Range constructors return flat lists of inclusive endpoint pairs.",
        "Folding keys map each code point with a simple case folding to the next",
        'member of its folding orbit (`k` -> `K` -> KELVIN SIGN -> `k`)."""',
        "",
    ]
    for name in ("WORD", "DIGIT", "SPACE"):
        values = [cp for pair in sets[name] for cp in pair]
        text.append("\n" + numeric_constructor(name.lower() + "_ranges", values) + "\n")
    text.append("\n" + numeric_constructor("fold_keys", [a for a, _ in pairs]) + "\n")
    text.append("\n" + numeric_constructor("fold_next", [b for _, b in pairs]))
    return "\n".join(text) + "\n"


def main() -> None:
    cps = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]
    column = pl.Series("s", [chr(c) for c in cps])
    sets = {}
    for name, pattern in (("WORD", r"^\w$"), ("DIGIT", r"^\d$"), ("SPACE", r"^\s$")):
        hits = column.str.contains(pattern).to_list()
        sets[name] = ranges([c for c, hit in zip(cps, hits) if hit])

    candidates = set()
    for c in cps:
        for mapped in (chr(c).lower(), chr(c).upper(), chr(c).casefold(), chr(c).title()):
            if mapped != chr(c):
                candidates.add(c)
                if len(mapped) == 1:
                    candidates.add(ord(mapped))
    candidates = sorted(candidates)
    cased = pl.Series("s", [chr(c) for c in candidates])
    orbits: dict[int, list[int]] = {}
    for c in candidates:
        hits = cased.str.contains("(?i)^\\x{%X}$" % c).to_list()
        orbit = [x for x, hit in zip(candidates, hits) if hit]
        if len(orbit) > 1:
            orbits[c] = orbit
    # Nothing outside the candidates may fold onto one of them.
    folded = "(?i)^[" + "".join("\\x{%X}" % c for c in orbits) + "]$"
    hits = column.str.contains(folded).to_list()
    stray = [c for c, hit in zip(cps, hits) if hit and c not in orbits]
    assert not stray, stray
    pairs = []
    for c, orbit in sorted(orbits.items()):
        assert orbits[orbit[0]] == orbit
        pairs.append((c, orbit[(orbit.index(c) + 1) % len(orbit)]))

    OUT.write_text(render(sets, pairs, pl.__version__))


if __name__ == "__main__":
    main()
